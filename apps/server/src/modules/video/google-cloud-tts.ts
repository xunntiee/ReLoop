import { randomUUID } from "node:crypto";
import type { ToolConfig } from "@tool-base/config/schema";
import type { TextToSpeechProvider } from "./tts-provider.js";
import type { VideoVoiceSettings } from "./types.js";

export interface GoogleCloudTtsResult {
  audioBytes: Buffer;
  message: string;
  provider: "google_cloud";
  requestId: string;
  status: "ready";
}

export class GoogleCloudTtsClient implements TextToSpeechProvider {
  readonly providerId = "google_cloud";

  constructor(private readonly config: ToolConfig["video"]) {}

  async synthesize(
    text: string,
    voiceSettings?: VideoVoiceSettings | null
  ): Promise<GoogleCloudTtsResult> {
    const apiKey = this.config.googleCloudApiKey.trim();
    if (!apiKey) {
      throw new Error(
        "Missing Google Cloud TTS API key. Set GOOGLE_CLOUD_TTS_API_KEY or config.video.googleCloudApiKey."
      );
    }

    const voiceConfig = {
      languageCode:
        voiceSettings?.languageCode || this.config.googleCloudLanguageCode,
      pitch:
        voiceSettings?.pitch !== undefined
          ? voiceSettings.pitch
          : this.config.googleCloudPitch,
      ssmlGender:
        voiceSettings?.ssmlGender || this.config.googleCloudSsmlGender,
      voiceName: voiceSettings?.voiceName || this.config.googleCloudVoiceName,
    };

    const endpoint = new URL(this.config.googleCloudBaseUrl);
    endpoint.searchParams.set("key", apiKey);
    const audioConfig: {
      audioEncoding: ToolConfig["video"]["googleCloudAudioEncoding"];
      pitch?: number;
      speakingRate?: number;
    } = {
      audioEncoding: this.config.googleCloudAudioEncoding,
      // Normalize provider output so all speed changes are applied locally.
      speakingRate: 1,
    };
    if (supportsPitchControl(voiceConfig.voiceName)) {
      audioConfig.pitch = voiceConfig.pitch;
    }

    const response = await fetch(endpoint, {
      body: JSON.stringify({
        audioConfig,
        input: {
          text,
        },
        voice: {
          ...(voiceConfig.voiceName ? { name: voiceConfig.voiceName } : {}),
          languageCode: voiceConfig.languageCode,
          ssmlGender: voiceConfig.ssmlGender,
        },
      }),
      headers: {
        "Content-Type": "application/json",
      },
      method: "POST",
    });

    if (!response.ok) {
      let errorMessage = `Google Cloud TTS request failed: ${response.status}`;
      try {
        const payload = (await response.json()) as {
          error?: {
            message?: string;
          };
        };
        if (payload.error?.message) {
          errorMessage = payload.error.message;
        }
      } catch {
        errorMessage = `Google Cloud TTS request failed: ${response.status}`;
      }
      throw new Error(errorMessage);
    }

    const payload = (await response.json()) as {
      audioContent?: string;
    };
    const audioContent = String(payload.audioContent ?? "").trim();
    if (!audioContent) {
      throw new Error("Google Cloud TTS did not return audioContent.");
    }

    return {
      audioBytes: Buffer.from(audioContent, "base64"),
      message: "Audio generated by Google Cloud TTS.",
      provider: "google_cloud",
      requestId:
        String(response.headers.get("x-request-id") ?? "").trim() ||
        randomUUID(),
      status: "ready",
    };
  }
}

function supportsPitchControl(voiceName: string): boolean {
  return !voiceName.includes("-Chirp3-HD-");
}
